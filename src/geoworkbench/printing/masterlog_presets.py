def _a4_form_preset(
    profile_id: str,
    profile_names: dict[AppLanguage, str],
    *,
    orientation: str,
) -> MasterlogFormPreset:
    header_id = f"a4_{profile_id}_{orientation}"
    header = next(item for item in CURATED_MASTERLOG_HEADER_PRESETS if item.preset_id == header_id)
    orientation_names = {
        "portrait": _texts("книжная", "кітаптық", "portrait"),
        "landscape": _texts("альбомная", "альбомдық", "landscape"),
    }[orientation]
    names = {
        language: f"{profile_names[language]} — A4, {orientation_names[language]}"
        for language in AppLanguage
    }
    descriptions = {
        AppLanguage.RU: "Готовая форма колонок с автоматически согласованной печатной шапкой.",
        AppLanguage.KK: "Автоматты түрде келісілген баспа тақырыбы бар дайын баған пішіні.",
        AppLanguage.EN: "Ready column layout with an automatically paired print header.",
    }
    return MasterlogFormPreset(
        f"a4_{profile_id}_{orientation}",
        names,
        descriptions,
        MasterlogTemplate(
            f"preset:a4_{profile_id}_{orientation}",
            names[AppLanguage.RU],
            page_format="A4",
            depth_scale=500,
            header_height_mm=header.height_mm,
            header_elements=list(deepcopy(header.elements)),
            columns=_scaled_a4_columns(_A4_FORM_PROFILE_COLUMNS[profile_id], orientation),
            properties={
                "preset_origin": f"a4_{profile_id}_{orientation}",
                "print_profile_id": profile_id,
                "paired_header_preset_id": header_id,
                "orientation": orientation,
            },
        ),
    )


CURATED_MASTERLOG_FORM_PRESETS = tuple(
    _a4_form_preset(profile_id, names, orientation=orientation)
    for profile_id, names, _title in _A4_HEADER_PROFILES
    for orientation in ("portrait", "landscape")
)

LEGACY_MASTERLOG_FORM_PRESETS = BUILTIN_MASTERLOG_FORM_PRESETS
BUILTIN_MASTERLOG_FORM_PRESETS = LEGACY_MASTERLOG_FORM_PRESETS + CURATED_MASTERLOG_FORM_PRESETS


def builtin_form_preset(preset_id: str) -> MasterlogFormPreset:
    try:
        return next(item for item in BUILTIN_MASTERLOG_FORM_PRESETS if item.preset_id == preset_id)
    except StopIteration as exc:
        raise KeyError(f"Встроенный образец masterlog не найден: {preset_id}") from exc


def builtin_header_preset(preset_id: str) -> MasterlogHeaderPreset:
    try:
        return next(
            item for item in BUILTIN_MASTERLOG_HEADER_PRESETS if item.preset_id == preset_id
        )
    except StopIteration as exc:
        raise KeyError(f"Встроенный образец шапки не найден: {preset_id}") from exc
