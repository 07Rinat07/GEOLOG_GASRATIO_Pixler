def _a4_profile_header(
    profile_id: str,
    profile_names: dict[AppLanguage, str],
    *,
    title: str,
    orientation: str,
) -> MasterlogHeaderPreset:
    """Build one restrained A4 header whose geometry matches its orientation."""

    if orientation not in {"portrait", "landscape"}:
        raise ValueError("A4 header orientation must be portrait or landscape")
    page_width = 210.0 if orientation == "portrait" else 297.0
    margin = 5.0
    gap = 2.0
    usable = page_width - margin * 2.0
    group_width = (usable - gap * 2.0) / 3.0
    label_width = min(26.0, group_width * 0.40)
    height = 34.0
    elements: list[MasterlogHeaderElement] = [
        _element(
            f"{profile_id}_{orientation}_title",
            "text",
            margin,
            2.0,
            usable,
            6.5,
            text=title,
            font_size_mm=4.6,
            bold=False,
            alignment="center",
            frame=True,
            background="#e2e8f0",
            color="#0f172a",
        )
    ]
    rows = (
        (
            ("ПРОЕКТ", "project.name"),
            ("СКВАЖИНА", "well.name"),
            ("ИНТЕРВАЛ", "header.interval"),
        ),
        (
            ("ЗАКАЗЧИК", "header.customer"),
            ("ИСПОЛНИТЕЛЬ", "header.contractor"),
            ("БУРОВАЯ", "header.rig"),
        ),
        (
            ("ФАЙЛ", "dataset.source_name"),
            ("СПЕЦИАЛИСТЫ", "header.engineers"),
            ("МАСШТАБ", "header.scale"),
        ),
    )
    for row_index, row in enumerate(rows):
        y = 10.0 + row_index * 7.0
        for column_index, (label, field_name) in enumerate(row):
            x = margin + column_index * (group_width + gap)
            element_prefix = f"{profile_id}_{orientation}_{row_index}_{column_index}"
            elements.extend(
                (
                    _element(
                        f"{element_prefix}_label",
                        "text",
                        x,
                        y,
                        label_width,
                        5.5,
                        text=label,
                        font_size_mm=1.8,
                        bold=False,
                        alignment="center",
                        word_wrap=False,
                        frame=True,
                        background="#f8fafc",
                        color="#334155",
                    ),
                    _element(
                        f"{element_prefix}_field",
                        "field",
                        x + label_width,
                        y,
                        group_width - label_width,
                        5.5,
                        field=field_name,
                        font_size_mm=2.2,
                        frame=True,
                        color="#0f172a",
                        missing_text="",
                    ),
                )
            )
    orientation_names = {
        "portrait": _texts("книжная", "кітаптық", "portrait"),
        "landscape": _texts("альбомная", "альбомдық", "landscape"),
    }[orientation]
    names = {
        language: f"{profile_names[language]} — A4, {orientation_names[language]}"
        for language in AppLanguage
    }
    descriptions = {
        AppLanguage.RU: (
            "Автоматически согласованная шапка для выбранной формы колонок; "
            f"A4, {orientation_names[AppLanguage.RU]}."
        ),
        AppLanguage.KK: (
            "Таңдалған баған пішінімен автоматты түрде келісілген тақырып; "
            f"A4, {orientation_names[AppLanguage.KK]}."
        ),
        AppLanguage.EN: (
            "Automatically paired header for the selected column form; "
            f"A4 {orientation_names[AppLanguage.EN]}."
        ),
    }
    return MasterlogHeaderPreset(
        f"a4_{profile_id}_{orientation}",
        names,
        descriptions,
        height,
        tuple(elements),
        orientation,
    )


