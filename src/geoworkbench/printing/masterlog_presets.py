def _scaled_a4_columns(
    columns: list[MasterlogColumnTemplate], orientation: str
) -> list[MasterlogColumnTemplate]:
    target_width = 200.0 if orientation == "portrait" else 287.0
    result = deepcopy(columns)
    total = sum(column.width_mm for column in result)
    if total <= 0:
        return result
    for column in result:
        column.width_mm = target_width * column.width_mm / total
    return result


