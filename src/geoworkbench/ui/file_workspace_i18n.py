def normalize_language(language: str) -> str:
    value = (language or "ru").split("-", 1)[0].casefold()
    return value if value in SUPPORTED_LANGUAGES else "ru"


def text(language: str, key: str, **values: object) -> str:
    lang = normalize_language(language)
    template = _TEXTS[lang].get(key, _TEXTS["ru"].get(key, key))
    return template.format(**values)


def catalogs_have_same_keys() -> bool:
    key_sets = [set(items) for items in _TEXTS.values()]
    return all(keys == key_sets[0] for keys in key_sets[1:])
